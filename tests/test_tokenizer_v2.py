    assert reloaded.pretokenizer_version == PRETOKENIZER_V2
    assert reloaded.decode(reloaded.encode(HELD_OUT, add_special_tokens=False), True) == HELD_OUT

    runtime = AdvancedBPETokenizer(vocab_file=path)
    assert runtime.pretokenizer_version == PRETOKENIZER_V2


