"""
Tokenizer v2 pre-tokenization tests.

Two jobs, in order of importance:

1. V1 MUST NOT MOVE.  The served v8 model was trained against the live
   4718-token vocab and its exact v1 tokenization.  Any change to v1
   encode/decode output silently corrupts every prompt the model sees.
   ``test_v1_*`` pins that behaviour with hardcoded IDs generated from
   the code as it stood BEFORE v2 existed.  If one of those fails, v2
   work has leaked into v1 -- fix v2, never the expected IDs.

2. v2 does what it claims: leading spaces attached to words, one token
   per digit, and lossless round-tripping.

Non-ASCII fixtures are written as escape sequences (\\u00e9 etc.) rather
than literal characters so this file stays pure ASCII on disk and does
not trip the repo hygiene gates in tests/test_repo_hygiene.py.
"""

