# A few KB of ordinary English prose, so the chars/token comparison is
# decisive rather than a tiny-corpus artefact.
PROSE = (
    "It is a truth universally acknowledged that a single man in possession of a good "
    "fortune must be in want of a wife. However little known the feelings or views of "
    "such a man may be on his first entering a neighbourhood, this truth is so well "
    "fixed in the minds of the surrounding families that he is considered as the "
    "rightful property of some one or other of their daughters. My dear Mr Bennet, "
    "said his lady to him one day, have you heard that Netherfield Park is let at last? "
    "Mr Bennet replied that he had not. But it is, returned she, for Mrs Long has just "
    "been here and she told me all about it. Mr Bennet made no answer. Do you not want "
    "to know who has taken it? cried his wife impatiently. You want to tell me and I "
    "have no objection to hearing it. This was invitation enough. Why my dear you must "
    "know Mrs Long says that Netherfield is taken by a young man of large fortune from "
    "the north of England, that he came down on Monday in a chaise and four to see the "
    "place and was so much delighted with it that he agreed with Mr Morris immediately. "
    "He is to take possession before Michaelmas and some of his servants are to be in "
    "the house by the end of next week. What is his name? Bingley. Is he married or "
    "single? Oh single my dear to be sure. A single man of large fortune, four or five "
    "thousand a year. What a fine thing for our girls. How so? How can it affect them? "
) * 3

PROSE_HELD_OUT = (
    "My dear Mr Bennet, said his lady, a single man of good fortune must be in want of "
    "a wife, and the surrounding families know it well before the end of next week."
)


def _chars_per_token(tokenizer, text: str) -> float:
    return len(text) / len(tokenizer.encode(text, add_special_tokens=False))


def test_v2_is_more_efficient_than_v1(tmp_path):
    """Same corpus, same target vocab size, same runtime class -- the
    only difference is the pre-tokenizer.

    Measured with AdvancedBPETokenizer (the class that actually encodes
    for the model) rather than BPETokenizer, because v1's trainer-side
    encode silently DROPS whitespace, which would flatter v1 with a
    chars/token figure for text it cannot reconstruct.
    """
    v1_path = tmp_path / "v1.json"
    v2_path = tmp_path / "v2.json"

    t1 = BPETokenizer()
    t1.train([PROSE], vocab_size=1000, min_frequency=2, verbose=False)
    t1.save(v1_path)

    t2 = BPETokenizer(pretokenizer=PRETOKENIZER_V2)
    t2.train([PROSE], vocab_size=1000, min_frequency=2, verbose=False)
    t2.save(v2_path)

    r1 = AdvancedBPETokenizer(vocab_file=v1_path)
    r2 = AdvancedBPETokenizer(vocab_file=v2_path)

    cpt1 = _chars_per_token(r1, PROSE_HELD_OUT)
    cpt2 = _chars_per_token(r2, PROSE_HELD_OUT)

    assert cpt2 > cpt1, f"v2 ({cpt2:.3f} chars/token) did not beat v1 ({cpt1:.3f})"
    # Only v2 can actually reconstruct the text it encoded.
    assert r2.decode(r2.encode(PROSE_HELD_OUT, add_special_tokens=False), True) == PROSE_HELD_OUT


